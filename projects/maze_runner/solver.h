/* ============================================================================
 * solver.h —— 搜索算法的接口：四个算法 + 两个结果结构体
 * ----------------------------------------------------------------------------
 * 这个文件负责什么：
 *   只回答一个问题：「给定一张地图，能走到吗？最短几步？路是怎么走的？」
 *   四个算法各管一件事，互不调用（连通块里那个 flood fill 长得像 DFS，
 *   但它数的是「全图分几块」，跟起点终点无关）：
 *
 *     dfsReachable     DFS 走一遍：判可达 + 数清「从起点踩得到的格子有几个」，
 *                      外加「DFS 顺手找到的第一条路」（故意给出来，好让你看见它不最短）
 *     bfsShortest      BFS：最短步数 + 用前驱表还原**完整路径**
 *     countComponents  全图连通块个数（多源 flood fill）
 *     bfsMultiSource   多个起点同时往外扩散，给每格算「到最近源点要几步」
 *
 * 为什么这样拆：
 *   算法只读地图（参数是 const Maze&），只返回结果结构体，不打印任何东西。
 *   「打印结果」和「assert 结果」都在 main.cpp。这样同一套 solver.* 可以直接
 *   搬去解洛谷上的迷宫题，只要换一个 main。
 *
 * 为什么结果用 struct 而不是一堆输出参数：
 *   notes/05 第 4 节那个 struct Result { bool ok; int steps; vector<int> path; }
 *   —— 一个函数要同时告诉你「到没到」「几步」「怎么走」，用引用参数传出三样东西，
 *   在调用点完全看不出发生了什么。返回一个命名结构体，调用方写 res.steps，
 *   读的人一眼就知道这个数在说什么。
 *
 * 坐标统一用 std::pair<int,int>：.first = 行 r，.second = 列 c。
 *   不自定义 struct Pos，是因为 pair 自带 == 和 <，能直接进 vector、能 sort，
 *   而且 notes/07 第 6 节点名了「两个量天然成对（坐标）就用 pair」。
 *   （讲义没教 using 别名，所以本文件老老实实写全类型名——多打几个字，
 *     换来的是每个签名都不用翻别处才知道 Cell 是什么。）
 * ========================================================================== */

#ifndef SOLVER_H
#define SOLVER_H

#include <utility>      /* std::pair */
#include <vector>

#include "maze.h"       /* 签名里出现了 Maze，所以必须自己 include，别指望调用方帮你包 */

/* ---------------------------------------------------------------------------
 * DFS 的结果。字段一律给默认值：「没走到」必须是 false / 0 / -1，
 * 不能是垃圾值（notes/07 第 1 节）。
 * ------------------------------------------------------------------------- */
struct DfsResult {
    bool reachable = false;              // 终点走得到吗
    int  visitedCells = 0;               // 从起点四方向能踩到的格子数（含起点自己）
    int  steps = -1;                     // DFS 找到的第一条路走了几步；不可达就是 -1
    std::vector<std::pair<int, int>> path;   // 那条路（DFS 的顺序，**不保证最短**）
};

/* BFS 的结果。steps 恒等于 path.size() - 1，main.cpp 里逐条钉这个等式。 */
struct PathResult {
    bool reachable = false;
    int steps = -1;                      // 最短步数（边权为 1 时的 BFS 距离）；不可达 -1
    std::vector<std::pair<int, int>> path;   // path[0] = 起点，最后一个 = 终点
};

/* ===========================================================================
 * 一、DFS：一条路走到黑
 * ---------------------------------------------------------------------------
 * dfsReachable(m) 用迷宫自带的 S/T，等价于 dfsExplore(m, m.start(), m.target())。
 * 它**会把整张图走满**（要数 visitedCells），不是找到终点就停，
 * 所以「可达」和「DFS 那条路」是同一次遍历顺手得到的两个结果。
 * src 是墙或者界外：直接返回「不可达 + 0 格」，不崩。
 * 把 dfsExplore 单独暴露出来，main.cpp 才能拿「起点==终点」「起点是墙」
 * 这些刁钻输入去测它。
 * ========================================================================= */
DfsResult dfsReachable(const Maze& m);
DfsResult dfsExplore(const Maze& m, std::pair<int, int> src, std::pair<int, int> dst);

/* ===========================================================================
 * 二、BFS：一层层往外扩，第一次到达终点就是最短
 * ---------------------------------------------------------------------------
 * 边权全是 1（走一格算一步）时，BFS 的层号 = 最短步数；这是 notes/11 第 3 节
 * 那句话的全部内容，也是 DFS 永远做不到的事。
 * 起点或终点是墙 / 界外：reachable = false、steps = -1、path 为空。
 * 起点 == 终点：reachable = true、steps = 0、path 只有一个格子（一步不用走）。
 * ========================================================================= */
PathResult bfsShortest(const Maze& m);
PathResult bfsPath(const Maze& m, std::pair<int, int> src, std::pair<int, int> dst);

/* ===========================================================================
 * 三、连通块：这张图被墙切成了几块
 * ---------------------------------------------------------------------------
 * 把每一格都当一次「没去过的起点」，去一次就 flood fill 一整块，
 * 块数就是答案。和起点终点无关，所以它是「全图统计」。
 * componentSizes 额外给出每块多大（按「从上到下、从左到右」第一次扫到该块的顺序），
 * 有了它才能写出「各块大小之和 == 能踩的格子总数」这种交叉验证。
 * ========================================================================= */
int countComponents(const Maze& m);
std::vector<int> componentSizes(const Maze& m);

/* ===========================================================================
 * 四、多源 BFS：好几个点同时开始扩散
 * ---------------------------------------------------------------------------
 * 做法和单源只差一步：开局把所有源点全塞进队列、dist 一律写 0，然后原样跑。
 * 得到的 dist[r][c] = 「(r,c) 到**最近那个**源点要几步」。
 * 典型题：多个出口问哪个先跑到、腐烂的橘子（烂橘子就是源点）、
 *        「地图上离任何一个基地最远的那个格子有多远」。
 * 界外 / 墙 / 重复的源点会被跳过，不会崩；到不了的格子保持 -1。
 * ========================================================================= */
std::vector<std::vector<int>> bfsMultiSource(
    const Maze& m,
    const std::vector<std::pair<int, int>>& sources);

#endif /* SOLVER_H */
