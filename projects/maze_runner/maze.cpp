/* ============================================================================
 * maze.cpp —— 地图模型的实现 + 四张内置样例
 * ----------------------------------------------------------------------------
 * 这个文件负责什么：
 *   把 maze.h 里声明的构造函数、at / passable / countPassable / render 填上身体，
 *   再摆出四张地图。
 *
 * 为什么这样拆：
 *   1. 声明与定义分开，才能分离编译：改一行 render，只有 maze.o 重编，
 *      solver.o / main.o 一个字节都不动（Makefile 那三行 [CXX] 就是证据）。
 *   2. 这个文件一行 cout 都没有。地图一旦会自己打印，就没法在别的场合复用
 *      （画到 OLED 屏上、写成字符串去 assert、发进串口），也没法干净地测。
 *      打印全部待在 main.cpp。
 *   3. 只 include 自己的头文件和标准库，绝不 include solver.h ——
 *      地图不知道搜索器的存在，依赖方向永远是「算法 -> 数据」。
 * ========================================================================== */

#include "maze.h"

/* ============================================================================
 * 构造函数：把一张「参差不齐的字符串数组」整理成一个可以安全查询的矩形网格
 * ----------------------------------------------------------------------------
 * 三件事按顺序做，缺一不可：
 *   ① 量出最宽的一行 -> cols_
 *   ② 把矮一截的行用墙补齐 -> 从此每行长度都是 cols_
 *   ③ 扫一遍找 S 和 T（只认第一个）
 *
 * ② 为什么要补：手写地图少敲一个字符太常见了。不补的话 g_[1].size() 可能
 * 比 cols_ 小，而 inBounds 只比到 cols_，于是 g_[1][cols_-1] 就是**越界读**
 * —— 编译不报错、运行不一定崩，崩在别的地方。补齐成矩形之后，
 * 「行内越界」这件事在物理上就不存在了，passable 只需要判列。
 * 补墙而不是补空地：宁可让地图比想象中更严一点，也不要凭空多出一条路。
 * ========================================================================== */
Maze::Maze(const std::vector<std::string>& rows)
    : g_(rows),                                   /* 先拷贝一份：外部那张图改不动它 */
      rows_((int)rows.size()),
      cols_(0),
      start_(-1, -1),                             /* -1 = 「还没找到」，notes/14 的约定 */
      target_(-1, -1)
{
    /* 初始化列表的顺序必须和上面字段声明的顺序一致，反了会吃 -Wreorder：
     * 构造时字段是**按声明顺序**初始化的，写反了就可能读到还没赋值的字段。 */

    for (const std::string& row : rows)
        if ((int)row.size() > cols_)
            cols_ = (int)row.size();              /* (int) 强转：size() 是无符号的 */

    for (std::string& row : g_)
        if ((int)row.size() < cols_)
            row.append((size_t)(cols_ - (int)row.size()), kWall);

    for (int r = 0; r < rows_; r++)
        for (int c = 0; c < cols_; c++) {
            /* S 和 T 各只认第一次出现的位置。写两张 S 也只用左上角那一个，
             * 这样「多写了个 S」不会让搜索静默地从两个地方同时出发。 */
            if (g_[(size_t)r][(size_t)c] == kStart && start_.first < 0)
                start_ = {r, c};
            else if (g_[(size_t)r][(size_t)c] == kTarget && target_.first < 0)
                target_ = {r, c};
        }
}

/* ----------------------------------------------------------------------------
 * 取字符。**界外一律返回 kWall**，这是整个项目里最省事的一个设计决定：
 *
 *   搜索代码每走一步都要问「(nr,nc) 能踩吗」，一共四类调用点（DFS、BFS、
 *   多源 BFS、连通块）。如果 at() 对越界返回垃圾或干脆崩，那四处都得先写一遍
 *   if (nr < 0 || nr >= rows || ...)；漏写一处就是一次越界读
 *   （notes/11 第 7 节第 3 条：顺序永远是先判越界、再访问数组）。
 *
 *   现在「界外 == 墙」，passable 一个函数把越界和撞墙两件事一起挡掉，
 *   判断只写一次、只在一个地方可能写错。语义上也说得通：地图外面当然是走不出去。
 * -------------------------------------------------------------------------- */
char Maze::at(int r, int c) const
{
    if (!inBounds(r, c)) return kWall;
    return g_[(size_t)r][(size_t)c];
}

bool Maze::passable(int r, int c) const
{
    /* 就一行，但它是「先判越界再访问」这条铁律唯一被写的地方。
     * at() 内部已经先调了 inBounds，所以这里绝不可能越界读。 */
    return at(r, c) != kWall;
}

int Maze::countPassable() const
{
    int n = 0;
    for (int r = 0; r < rows_; r++)
        for (int c = 0; c < cols_; c++)
            if (passable(r, c)) n++;      /* 能踩 = 空地 + S + T，注意 S/T 也算 */
    return n;
}

/* ============================================================================
 * render：把路径画回地图
 * ----------------------------------------------------------------------------
 * 返回一张**新图**，本对象一个字都不改（函数是 const 的，改不了）。
 * 三条渲染规则都在防「脏数据画出鬼东西」：
 *   - 界外坐标：跳过（main.cpp 里故意塞一个 (9,9) 进来测这条）；
 *   - S / T：保留原字符，不然图上看不出头尾在哪；
 *   - 墙：即使路径里混进了墙格也不画 —— 路径合法性另有函数在 main.cpp 里查，
 *     渲染函数不负责纠错，它只保证「画出去的一定不撒谎」。
 * ========================================================================== */
std::vector<std::string> Maze::render(const std::vector<std::pair<int, int>>& path) const
{
    std::vector<std::string> out = g_;        /* 拷贝，不是引用：原图不动 */

    for (const std::pair<int, int>& p : path) {
        const int r = p.first;
        const int c = p.second;
        if (!inBounds(r, c)) continue;
        const char ch = out[(size_t)r][(size_t)c];
        if (ch == kStart || ch == kTarget || ch == kWall) continue;
        out[(size_t)r][(size_t)c] = kPath;
    }
    return out;
}

/* ============================================================================
 * 内置样例。想换地图就改这里，改完记得跑 make p2 ——
 * main.cpp 里那些写死的期望值（10 步 / 27 格 / 3 个连通块）会立刻告诉你
 * 哪些数字跟着变了。这是「数据变了测试先炸」，比「测试跟着一起改坏」好得多。
 * ========================================================================== */

/* 3×4：一条道走到底，人眼可验证，用来当所有算法的基准。
 * 8 个能踩的格子 + 4 堵墙 = 12 格，(0,0) -> (2,3) 最短 5 步。 */
Maze mazeTiny()
{
    return Maze({"S..#",
                 "##.#",
                 "...T"});
}

/* 5×7：notes/11 第 3 节、exercises/ex12 里实测过的那一张（(0,0)->(4,6) = 10 步）。
 * 只改了三个字符：左上角的 '.' 换成 S，右下角的 '.' 换成 T —— 墙一根没动，
 * 所以讲义里那个 10 必须照样成立。这就是本项目对讲义的一次「交叉验证」。 */
Maze mazeClassic()
{
    return Maze({"S#.....",
                 "...#..#",
                 ".#...#.",
                 "..#....",
                 "..#.#.T"});
}

/* 4×4：第 2 列下半段 + 第 2 行右半段把图彻底切开，起点那侧 5 格、
 * 终点那侧 2 格，中间没有任何缝。专门用来考「不可达」这条返回路径：
 * 可达标志必须是 false，步数必须是 -1，路径必须是空 vector。 */
Maze mazeNoWay()
{
    return Maze({"S.##",
                 "..##",
                 ".###",
                 "##.T"});
}

/* 5×9：三间互相封死的房（第 2 列、第 6 列是整根柱子）。
 * 左房 9 格（S、T 都在里面，最短 4 步）、中房 12 格、右房 8 格，
 * 一共 29 个能踩的格子 -> 连通块恒等于 3。
 * 它的用途：验证「从起点走不到的格子照样算在连通块里」——
 * DFS 只会数出 9，countComponents 必须数出 3 块、29 格。 */
Maze mazeIslands()
{
    return Maze({"S.#...#..",
                 "..#.#.#.#",
                 ".##.#.#..",
                 "..#...##.",
                 "T.#.#.#.."});
}
