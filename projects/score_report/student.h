/* ============================================================================
 * student.h —— 成绩报表项目的「数据模型」接口
 * ----------------------------------------------------------------------------
 * 这个文件负责什么：
 *   1. 定义一张表长什么样（struct Student + 科目数常量）
 *   2. 声明对「一个学生」能问哪些问题（总分、平均分、最高分……）
 *   3. 提供一份内置样例数据 sampleStudents()
 *
 * 为什么这样拆：
 *   头文件是「合同」，不是「实现」。这里只放类型、常量和函数声明，
 *   一个函数体都不写。报表怎么排版、表格画多宽，跟数据模型无关，
 *   所以那些东西在 report.h 里；这个文件里出现的每个名字都必须和
 *   「学生成绩」这件事本身有关，哪怕哪天换一套 UI 也不用改它。
 *
 * 嵌入式视角：先写 .h 再写 .c/.cpp 的习惯要现在养成。
 *   硬件接口（寄存器映射、驱动 API）一旦定下就很难改，
 *   接口先行能逼你在动手前想清楚「这个模块到底对外提供什么」。
 * ========================================================================== */

/* ----------------------------------------------------------------------------
 * 头文件守卫：为什么非要有这两行？
 *
 *   #include 在预处理阶段就是「把那个文件的内容原样贴进来」。
 *   report.cpp 里写了 #include "report.h"，而 report.h 又 #include "student.h"；
 *   如果哪天 main.cpp 同时直接 include 了这两个，student.h 就会被贴两遍，
 *   struct Student 出现两份定义 —— 编译器直接报 redefinition。
 *   守卫的作用：第一次进来把 STUDENT_H 这个宏定义掉，第二次整段跳过。
 *
 *   #pragma once 效果一样，现代编译器都认，但它不是标准里的东西。
 *   本仓库统一用 #ifndef/#define/#endif，因为它在任何编译器上都成立
 *   （嵌入式 IDE 里经常躺着一些上古版本的编译器）。
 *
 * #include <xxx> 与 #include "xxx" 的区别（notes/01 自检第 1 问）：
 *   <>  只在系统/标准库头文件目录里找  —— iostream、vector 这类
 *   ""  先在当前目录（和 -I 指定的目录）找，找不到再退到系统目录
 *   所以自己的 student.h 用引号，标准库用尖括号。写反了通常也编得过，
 *   但这两个符号同时是给读代码的人看的记号：「这是项目的」还是「这是语言的」。
 * -------------------------------------------------------------------------- */
#ifndef STUDENT_H
#define STUDENT_H

#include <string>
#include <vector>

/* 头文件里绝不写 using namespace std; 或 #include 之后直接假设它存在。
 * 原因：using 声明会顺着 #include 污染所有包含这个头文件的 .cpp，
 * 你没法阻止它。竞赛里写 std:: 太麻烦，所以练习文件的 .cpp 里才用
 * using namespace std;（那是单个自包含程序）；工程代码的 .h 里一律写全。 */

/* ----------------------------------------------------------------------------
 * 全班的科目表。写在头文件里是因为「科目有几门」是这套数据的定义的一部分，
 * report.cpp 排表格、main.cpp 造数据都要用到它。
 * constexpr = 编译期就把值定死，编译器能拿它检查数组长度、能做常量折叠。
 * ------------------------------------------------------------------------- */
constexpr int kSubjectCount = 4;
constexpr int kScoreMax = 100;          // 单科满分，用来做「最值初始化」的上界

/* ----------------------------------------------------------------------------
 * 一个学生 = 表里的一行。
 *
 *   字段一律给默认值：notes/07 讲过，局部变量的字段是垃圾值，
 *   Student s; 然后忘赋分，报表就会打出莫名其妙的数字。
 *
 *   scores 用 vector<int> 而不是 int scores[4]：
 *     - 结构体可以整体赋值、可以比较、能安全地塞进 vector<Student>
 *     - 原生数组字段会让结构体不能 = 赋值（notes/06 第 1 节）
 *   代价是每次拷贝学生都要拷一遍堆内存 —— 所以传参一律 const Student&，
 *   这条规则在 notes/07 第 3 节写着，本项目里没有一处例外。
 * ------------------------------------------------------------------------- */
struct Student {
    std::string name = "";
    int id = 0;
    std::vector<int> scores;            // 按 kSubjectName() 的顺序存 kSubjectCount 门
};

/* ----------------------------------------------------------------------------
 * 科目名。为什么用函数而不是在头文件里写 const vector<string> kSubjectNames?
 *   因为头文件里放「变量的定义」= 每个包含它的 .cpp 都生成一份，
 *   链接时报 multiple definition —— 这是多文件工程里最常见的错，
 *   和「函数定义写在头文件里」是同一个病根。
 *   用访问函数包一层，数据本体藏在 student.cpp 里（内部链接），干干净净。
 * ------------------------------------------------------------------------- */
const std::string& subjectName(int index);

/* ---------------------------------------------------------------------------
 * 下面这些全是「纯计算函数」：同样的输入必然给出同样的输出，
 * 不读键盘、不写屏、不碰全局状态。正因为纯，它们可以被 assert 逐条钉死
 * （main.cpp 就靠这一点做验收）。数据模型和打印分开，也是为了这个。
 * ------------------------------------------------------------------------- */

/* 总分。4 门 x 100 = 400，离 int 上限还差五个数量级，用 int 安全；
 * 但如果科目数或值域变大，第一件事就是把返回类型换成 long long。 */
int totalOf(const Student& s);

/* 平均分 = 总分 / 门数。没有成绩时返回 0.0 —— 除法前先想分母能不能为 0。 */
double avgOf(const Student& s);

/* 单科最高分 / 最低分。空成绩返回 -1，用 -1 而不是 0 表示「没有数据」，
 * 因为 0 是一个合法的分数（notes/14：表示「还没有合法答案」要用 -1）。 */
int maxScoreOf(const Student& s);
int minScoreOf(const Student& s);

/* 最高分出现在哪一门，返回下标；并列时取最小的下标。空成绩返回 -1。 */
int bestSubjectOf(const Student& s);

/* 挂科门数：严格低于 passLine 才算挂。恰好等于及格线不算（边界必须自己测）。 */
int failedCount(const Student& s, int passLine);

/* ---------------------------------------------------------------------------
 * 内置样例数据。本项目不从 stdin、也不从文件读数据：
 * make run 必须能在任何机器上非交互地跑完（CI、Windows、Linux 都一样）。
 * 数据里故意埋了并列，好让排序和名次逻辑被真正测到：
 *   Bob / Fiona 同总分 352，David 一个人 380，两个 Kevin 同名同总分不同学号。
 * 名字用 ASCII：控制台编码一乱，表格的列宽就对不上了（notes/03 讲过中文按字节算）。
 * ------------------------------------------------------------------------- */
std::vector<Student> sampleStudents();

#endif /* STUDENT_H */
